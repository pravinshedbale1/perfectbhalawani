function below1000(n, isLast) {
  const h = Math.floor(n / 100), r = n % 100, parts = [];
  if (h) parts.push(h === 1 ? (r || !isLast ? 'एकशे' : 'शंभर') : W[h] + 'शे');
  if (r) parts.push(W[r]);
  return parts.join(' ');
}

export function amountInWordsMr(amount) {
  let n = Math.floor(Math.abs(Number(amount) || 0));
  if (n === 0) return 'शून्य रुपये फक्त';
  const parts = [];
  const crore = Math.floor(n / 1e7); n %= 1e7;
  const lakh = Math.floor(n / 1e5); n %= 1e5;
  const thousand = Math.floor(n / 1000); n %= 1000;
  if (crore) parts.push(below1000(crore, false) + ' कोटी');
  if (lakh) parts.push(W[lakh] + ' लाख');
  if (thousand) parts.push(W[thousand] + ' हजार');
  if (n) parts.push(below1000(n, true));
  return parts.join(' ') + ' रुपये फक्त';
}
